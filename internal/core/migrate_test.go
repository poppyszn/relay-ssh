// legacyTree lays out what a machine looks like after running the tool under its old name.
func legacyTree(t *testing.T) paths.Paths {
	t.Helper()
	p := paths.New(t.TempDir())
	oldCfg, oldBox := p.LegacyConfigDir(), p.LegacySandbox()
	for _, d := range []string{oldCfg, filepath.Join(oldBox, "keys")} {
		if err := os.MkdirAll(d, 0o700); err != nil {
			t.Fatal(err)
		}
	}
	store := config.Store{Version: config.Version, Profiles: []config.Profile{
		{Name: "web", Host: "10.0.0.5", User: "deploy", Port: 22, Auth: config.AuthKey, Key: "id_ed25519"},
	}}
	if err := config.Save(filepath.Join(oldCfg, "connections.toml"), store); err != nil {
		t.Fatal(err)
	}
	must := func(path, body string) {
		if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	must(filepath.Join(oldBox, "keys", "id_ed25519"), "PRIVATE KEY")
	must(filepath.Join(oldBox, "config"), "# Managed by sssh. Do not edit this file.\nHost web\n  IdentityFile ~/.ssh/sssh.d/keys/id_ed25519\n")
	must(p.SSHConfig, "# >>> sssh managed block >>>\nInclude ~/.ssh/sssh.d/config\n# <<< sssh managed block <<<\n\nHost mine\n  HostName example.com\n")
	return p
}

func TestMigrateMovesAnOldTreeAndRepointsSSH(t *testing.T) {
	p := legacyTree(t)
	if err := Migrate(p); err != nil {
		t.Fatalf("Migrate: %v", err)
	}
	for _, gone := range []string{p.LegacyConfigDir(), p.LegacySandbox()} {
		if _, err := os.Stat(gone); err == nil {
			t.Errorf("%s should have moved", gone)
		}
	}
	if b, err := os.ReadFile(filepath.Join(p.KeysDir, "id_ed25519")); err != nil || string(b) != "PRIVATE KEY" {
		t.Fatalf("the adopted key did not come along: %q %v", b, err)
	}
	if _, err := config.Load(p.StoreFile); err != nil {
		t.Fatalf("connections did not come along: %v", err)
	}

	ssh, _ := os.ReadFile(p.SSHConfig)
	if strings.Contains(string(ssh), "sssh") {
		t.Errorf("~/.ssh/config still mentions the old name:\n%s", ssh)
	}
	if !strings.Contains(string(ssh), "Include ~/.ssh/relay-ssh.d/config") || !strings.Contains(string(ssh), "Host mine\n  HostName example.com") {
		t.Errorf("the block was not repointed, or the user's own lines changed:\n%s", ssh)
	}

	gen, _ := os.ReadFile(p.GenConfig)
	if strings.Contains(string(gen), "sssh") || !strings.Contains(string(gen), "~/.ssh/relay-ssh.d/keys/id_ed25519") {
		t.Errorf("the generated config was not rewritten for the new paths:\n%s", gen)
	}
}

func TestMigrateDoesNothingTwiceOrOnAFreshMachine(t *testing.T) {
	p := legacyTree(t)
	if err := Migrate(p); err != nil {
		t.Fatal(err)
	}
	before, _ := os.ReadFile(p.SSHConfig)
	if err := Migrate(p); err != nil {
		t.Fatal(err)
	}
	after, _ := os.ReadFile(p.SSHConfig)
	if string(before) != string(after) {
		t.Error("a second run changed ~/.ssh/config")
	}

	fresh := paths.New(t.TempDir())
	if err := Migrate(fresh); err != nil {
		t.Fatal(err)
	}
	if entries, _ := os.ReadDir(fresh.Root); len(entries) != 0 {
		t.Errorf("a fresh machine got %d new entries", len(entries))
	}
}

// If both an old and a new tree exist, the new one wins and the old one is left for the person to look at.
func TestMigrateNeverOverwritesAnExistingNewTree(t *testing.T) {
	p := legacyTree(t)
	if err := os.MkdirAll(p.ConfigDir, 0o700); err != nil {
		t.Fatal(err)
	}
	marker := filepath.Join(p.ConfigDir, "connections.toml")
	if err := os.WriteFile(marker, []byte("version = 1\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := Migrate(p); err != nil {
		t.Fatal(err)
	}
	if b, _ := os.ReadFile(marker); string(b) != "version = 1\n" {
		t.Errorf("the new store was overwritten: %q", b)
	}
	if _, err := os.Stat(filepath.Join(p.LegacyConfigDir(), "connections.toml")); err != nil {
		t.Error("the old store should be left where it was")
	}
}
